/* hosttests/data/libm_cases.h — the shared libm case table.
 *
 * ONE row is one function invocation.  The arguments are bit patterns, so
 * the table can express exact values (signed zeros, subnormals, NaN
 * payloads) without the compiler rounding them.
 *
 * The table is the single source of truth for the host test and for the
 * standalone glibc oracle (hosttests/oracle/libm_oracle.c): both walk it
 * in the same order, and the oracle prints one row per case.  The test
 * then compares the OS01 result with the oracle's, field by field.
 *
 * The comparison strategy per row:
 *
 *   LIBM_CMP_EXACT      the two bit patterns must be identical.  This is
 *                       the normal case: musl's base algebra is correctly
 *                       rounded, so it agrees with glibc bit for bit.
 *   LIBM_CMP_NAN        both results must be NaN, but the payloads may
 *                       differ.  A signaling NaN comes back unchanged
 *                       from OS01 while glibc quiets it.
 *   LIBM_CMP_FIXED_NAN  the OS01 result must be the FIXED quiet NaN
 *                       (0x7ff8000000000000 / 0x7fc00000).  This is the
 *                       contract for the invalid paths of sqrt and fmod.
 *
 * expect_errno is the errno the OS01 implementation must report after
 * the call: 0 means "errno must be UNCHANGED" (the sentinel survives),
 * EDOM means "errno must be EDOM".  The oracle's own errno is recorded
 * for diagnosis only -- the OS01 error contract is judged by this table.
 */
